import asyncio, os, time
from contextlib import asynccontextmanager

from fastapi import FastAPI, HTTPException
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field
from fastembed import TextEmbedding
from openai import AsyncOpenAI
from pgvector.psycopg import register_vector_async
from psycopg_pool import AsyncConnectionPool
from prometheus_client import Counter, Gauge, Histogram, make_asgi_app

from .search import HYBRID_SQL, search_params

# --- Settings (environment variables, with laptop defaults) ---
DATABASE_URL = os.getenv("DATABASE_URL", "postgresql://shop:shop@localhost:5432/shop")
LLM_BASE_URL = os.getenv("LLM_BASE_URL", "http://localhost:11434/v1")  # Ollama now, vLLM later
LLM_MODEL = os.getenv("LLM_MODEL", "llama3.2:3b")
LLM_API_KEY = os.getenv("LLM_API_KEY", "not-needed")
EMBED_MODEL = os.getenv("EMBED_MODEL", "BAAI/bge-small-en-v1.5")
DEFAULT_TOP_K = int(os.getenv("TOP_K", "5"))
MAX_TOKENS = int(os.getenv("MAX_TOKENS", "300"))

SYSTEM_PROMPT = (
    "You are the shopping assistant for an online store during its Black Friday sale. "
    "Answer using only the products provided. Recommend up to 3 that best fit the "
    "customer's needs and budget, and give each one's normal price and Black Friday price. "
    "If none of the products fit, say so honestly. Keep the answer short and friendly."
)

# --- Metrics, exposed at /metrics for Alloy to collect ---
LATENCY_BUCKETS = (0.05, 0.1, 0.25, 0.5, 1, 2, 3, 5, 8, 13, 20, 30, 60, 120)
RETRIEVAL = Histogram("rag_retrieval_seconds", "Embed the question and search Postgres",
                      buckets=LATENCY_BUCKETS)
TTFT = Histogram("rag_ttft_seconds", "Request start to first generated token",
                 buckets=LATENCY_BUCKETS)
TOTAL = Histogram("rag_request_seconds", "Request start to last token",
                  buckets=LATENCY_BUCKETS)
PROMPT_TOKENS = Histogram("rag_prompt_tokens", "Tokens sent to the model",
                          buckets=(250, 500, 750, 1000, 1500, 2000, 3000, 4000))
OUTPUT_TOKENS = Histogram("rag_output_tokens", "Tokens generated by the model",
                          buckets=(25, 50, 100, 150, 200, 300, 400, 600))
ERRORS = Counter("rag_errors_total", "Failed requests by stage", ["stage"])
IN_FLIGHT = Gauge("rag_requests_in_flight", "Requests currently being handled")

state = {}


async def configure_connection(conn):
    await register_vector_async(conn)  # lets psycopg send vectors


@asynccontextmanager
async def lifespan(app):
    # Runs once at startup: load the embedding model, open DB connections, create the LLM client
    state["embedder"] = TextEmbedding(EMBED_MODEL)
    state["pool"] = AsyncConnectionPool(DATABASE_URL, min_size=2, max_size=20,
                                        configure=configure_connection, open=False)
    await state["pool"].open()
    state["llm"] = AsyncOpenAI(base_url=LLM_BASE_URL, api_key=LLM_API_KEY, timeout=120)
    yield
    await state["pool"].close()


app = FastAPI(title="Shopping assistant", lifespan=lifespan)
app.mount("/metrics", make_asgi_app())


class AskRequest(BaseModel):
    question: str = Field(min_length=3, max_length=500)
    top_k: int = Field(DEFAULT_TOP_K, ge=1, le=15)  # how many products to retrieve


async def retrieve(question, top_k):
    # Embedding runs on CPU, so do it in a thread to avoid blocking other requests
    qvec = await asyncio.to_thread(lambda: next(state["embedder"].query_embed(question)))
    async with state["pool"].connection() as conn:
        cur = await conn.execute(HYBRID_SQL, search_params(question, qvec, top_k))
        return [row[4] for row in await cur.fetchall()]  # row[4] is the content


def build_messages(question, products):
    if products:
        context = "\n\n".join(f"[Product {i}]\n{p}" for i, p in enumerate(products, 1))
    else:
        context = "(no matching products found)"
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f"Products:\n{context}\n\nCustomer question: {question}"},
    ]


@app.get("/health")
async def health():
    return {"status": "ok"}


@app.post("/ask")
async def ask(req: AskRequest):
    start = time.perf_counter()
    IN_FLIGHT.inc()

    # 1. Retrieve
    try:
        t0 = time.perf_counter()
        products = await retrieve(req.question, req.top_k)
        RETRIEVAL.observe(time.perf_counter() - t0)
    except Exception as e:
        ERRORS.labels("retrieval").inc()
        IN_FLIGHT.dec()
        raise HTTPException(503, "Product search failed") from e

    # 2. Ask the LLM, streaming
    try:
        stream = await state["llm"].chat.completions.create(
            model=LLM_MODEL, messages=build_messages(req.question, products),
            max_tokens=MAX_TOKENS, temperature=0.3, stream=True,
            stream_options={"include_usage": True},
        )
    except Exception as e:
        ERRORS.labels("llm").inc()
        IN_FLIGHT.dec()
        raise HTTPException(502, "Model unavailable") from e

    usage = {}

    async def tokens():
        async for chunk in stream:
            if chunk.usage:  # the last chunk carries token counts
                usage["prompt"] = chunk.usage.prompt_tokens
                usage["output"] = chunk.usage.completion_tokens
            if chunk.choices and chunk.choices[0].delta.content:
                yield chunk.choices[0].delta.content

    # 3. Wait for the first token BEFORE responding, so time-to-first-byte = TTFT
    gen = tokens()
    try:
        first = await anext(gen)
    except StopAsyncIteration:
        first = ""
    except Exception as e:
        ERRORS.labels("llm").inc()
        IN_FLIGHT.dec()
        raise HTTPException(502, "Model stream failed") from e
    TTFT.observe(time.perf_counter() - start)

    # 4. Stream the rest, then record the totals
    async def body():
        try:
            yield first
            async for token in gen:
                yield token
        except Exception:
            ERRORS.labels("stream").inc()
        finally:
            TOTAL.observe(time.perf_counter() - start)
            if "prompt" in usage:
                PROMPT_TOKENS.observe(usage["prompt"])
                OUTPUT_TOKENS.observe(usage["output"])
            IN_FLIGHT.dec()

    return StreamingResponse(body(), media_type="text/plain; charset=utf-8")